package app.vdvoem.core.domain.device

/**
 * Стабильный идентификатор установки.
 *
 * Нужен, чтобы отличать «сюрпризы», созданные на этом устройстве, от сюрпризов партнёра:
 * первые видны всегда, вторые — нет. Реализация хранит значение локально (DataStore),
 * ядро о платформе ничего не знает.
 */
interface DeviceIdentity {
    suspend fun deviceId(): String
}